package com.sheen.rokid.plugin

/**
 * System-One (Laya) local decision service.
 *
 * System-One is a **decision model**, not a text generator: it answers one question about a state and returns a
 * labelled, probabilistic answer. The shape below is Laya's own question/answer schema, expressed without leaking
 * any `com.laya` type into this contract module — see the approved proposal
 * `docs/project/2026-10-13-systemone-interface-change-proposal.md`.
 *
 * **Why one `ask` and not three verbs.** The question *type* is data, not a method: every form carries
 * `instructions` (the proposition being judged) and the candidates differ only in how Laya renders and decodes
 * them. Three convenience verbs would each have to repeat `instructions` and would each need their own result
 * type, which is exactly how the previous signature ended up unable to carry a question at all.
 *
 * See spec §2.2.
 */
interface SystemOneService {
    /**
     * Puts one question to the local decision model about [state] and returns its answer.
     *
     * @param state Text describing the ambient context. Laya's prompt template places the instructions and the
     *   candidates *before* the state and truncates over-long content **from the end**, so a caller must put the
     *   fields the decision depends on first and the optional long text last.
     * @param question The question, its instructions and its criteria.
     * @return the answer with its latency, or a [SystemOneResult.Failure] — this call never throws for an
     *   unavailable model, because "the model is missing" and "the model answered zero" must not be the same value.
     */
    fun ask(state: String, question: SystemOneQuestion): SystemOneResult

    /** Whether the service is ready to accept inference calls. */
    val isAvailable: Boolean

    /** Current service status for UI display. */
    val status: SystemOneStatus

    /** Metadata about the loaded model, or null if not loaded. */
    val modelInfo: ModelInfo?
}

/** The three question forms Laya supports; the graph channel is choice=0, score=1, noul=2. */
enum class SystemOneQuestionType { CHOICE, SCORE, NOUL }

/**
 * One named candidate of a [SystemOneQuestion].
 *
 * CHOICE uses both fields: [label] is what the answer comes back under and [description] is what the model reads.
 * SCORE uses only [description] — the labels are the level indices, generated by the position.
 *
 * `description` is nullable because a SCORE level is a phrase, not a label/description pair, and a CHOICE whose
 * label is self-explanatory has nothing to add.
 */
data class SystemOneCriterion(val label: String, val description: String? = null) {
    init {
        require(label.isNotBlank()) { "criterion label must not be blank" }
    }
    // Redacted: a label is supplied by the caller and a general caller's labels are its own
    // vocabulary, which the "counts and ids only, never content" rule keeps out of anything that prints.
    override fun toString() = "SystemOneCriterion(redacted)"
}

/**
 * One question in Laya's own schema.
 *
 * **Criteria order is part of the contract**: Laya renders one marker per criterion and maps the decoded marker
 * positions back to criteria positions, so reordering the list silently relabels every answer.
 *
 * @param type which of the three forms this is.
 * @param instructions the question text — for the D60 proactive gate this is the proposition being judged, whose
 *   literal is pinned by the fine-tune spec (`docs/superpowers/specs/2026-10-13-laya-gate-finetune-design.md` §3.3)
 *   and not chosen here. A fine-tune trains on one exact string, so the trained string and the deployed string have
 *   to be the same one; this field being first-class is what keeps that possible.
 * @param criteria the candidates or scale levels. Required for [SystemOneQuestionType.CHOICE] and
 *   [SystemOneQuestionType.SCORE]; for [SystemOneQuestionType.NOUL] it is normally empty and the host renders its
 *   own default true/false option text.
 */
data class SystemOneQuestion(
    val type: SystemOneQuestionType,
    val instructions: String,
    val criteria: List<SystemOneCriterion> = emptyList(),
) {
    init {
        require(instructions.isNotBlank()) { "question instructions must not be blank" }
        // A CHOICE or SCORE question with no criteria asks for zero markers; Laya's decoder only rejects that as
        // "Logits/criteria option count mismatch" long after the question has left the caller's hands.
        require(type == SystemOneQuestionType.NOUL || criteria.isNotEmpty()) {
            "a $type question needs at least one criterion"
        }
    }
    override fun toString() = "SystemOneQuestion(type=$type, criteria=${criteria.size})"
}

/** What Laya answered. One variant per [SystemOneQuestionType]. */
sealed class SystemOneAnswer {
    /** A [SystemOneQuestionType.CHOICE] answer: the chosen label, the distribution over all labels, the confidence. */
    data class Choice(
        val choice: String,
        val probabilities: Map<String, Double>,
        val confidence: Double,
    ) : SystemOneAnswer() {
        // The distribution is keyed by criterion label, so the default data-class rendering would print them.
        override fun toString() = "SystemOneAnswer.Choice(options=${probabilities.size}, confidence=$confidence)"
    }

    /** A [SystemOneQuestionType.SCORE] answer: the expected level, the per-level distribution, the confidence. */
    data class Score(
        val level: Double,
        val probabilities: Map<String, Double>,
        val confidence: Double,
    ) : SystemOneAnswer()

    /** A [SystemOneQuestionType.NOUL] answer: the probability the statement holds, and the confidence. */
    data class Noul(
        val probability: Double,
        val confidence: Double,
    ) : SystemOneAnswer()
}

/**
 * The outcome of one [SystemOneService.ask].
 *
 * [Success.latencyMs] is part of the contract because the D60 proactive gate has to know what one judgement costs
 * before it can decide whether the call fits a path — the publisher's host already reports segment timings, so
 * making the caller time it separately would only add a second, disagreeing number.
 */
sealed class SystemOneResult {
    data class Success(val answer: SystemOneAnswer, val latencyMs: Double) : SystemOneResult() {
        init {
            require(latencyMs >= 0.0) { "latencyMs must not be negative, was $latencyMs" }
        }
        override fun toString() = "SystemOneResult.Success(latencyMs=$latencyMs)"
    }

    data class Failure(val reason: FailureReason, val message: String) : SystemOneResult() {
        init {
            require(message.isNotBlank()) { "failure message must not be blank" }
        }
        override fun toString() = "SystemOneResult.Failure(reason=$reason)"
    }
}

/** Service lifecycle status visible to the user. */
enum class SystemOneStatus {
    /** Model is being loaded asynchronously. */
    LOADING,
    /** Model is loaded and ready for inference. */
    READY,
    /** Model failed to load or was unloaded by the system. */
    UNAVAILABLE,
}

/** Metadata about a loaded local model. */
data class ModelInfo(
    val name: String,
    val version: String,
    val quantization: String,
    val parameterCount: String,
    val contextWindow: Int,
)

/**
 * Reasons a local model operation can fail.
 *
 * Shared by both local model services — [EmbeddingService] uses it for `EmbedResult.Error` too — so it outlives the
 * reshaped System-One contract and must not be deleted with it.
 */
enum class FailureReason {
    MODEL_NOT_LOADED,
    ENGINE_UNAVAILABLE,
    INFERENCE_TIMEOUT,
    INVALID_INPUT,
    RESOURCE_EXHAUSTED,
}
