package com.sheen.rokid.phone.inference.litert

import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File

/**
 * edith-0.2 Phase B, task 6b: the tokenizer half of `EmbeddingGemmaLiteRTEngine`, provable without the 179 MB graph.
 *
 * **The oracle is the publisher's own tokenizer.** Every expectation below was produced by running
 * `sentencepiece.SentencePieceProcessor` (python-sentencepiece 0.2.2) over `sentencepiece.model`, and is pasted in as
 * a literal. A hand-written expectation would only prove the author and the implementation agree.
 *
 * **The model is BPE, not unigram.** `TrainerSpec.model_type == 2`, so sentencepiece runs `bpe_model.cc` and never
 * `unigram_model.cc`; the evidence is `docs/project/evidence/2026-10-13-embeddinggemma-tokenizer-is-bpe.md`. The
 * consequence for this file is that every expectation is a *merge* outcome: `EDIT` survives as one piece because its
 * rank wins, not because any sum of scores is largest. A Viterbi over these scores reproduces only 19 of 68 strings.
 *
 * The model file is gitignored, so these tests skip — loudly, naming the path — when it is absent. That is the honest
 * structure: the alternative is committing 4.7 MB of vendor data to keep a test that proves nothing extra.
 */
class EmbeddingTokenizerTest {

    private fun repositoryRoot(): File =
        generateSequence(File("").absoluteFile) { it.parentFile }
            .firstOrNull { File(it, "settings.gradle.kts").isFile }
            ?: error("repository root not found from ${File("").absolutePath}")

    private val modelFile: File =
        File(repositoryRoot(), ".local/models/embeddinggemma/sentencepiece.model")

    /** The oracle corpus, generated by `.local/t6b2-corpus.py`; gitignored, so the test skips without it. */
    private val corpusFile: File = File(repositoryRoot(), ".local/t6b2-corpus.tsv")

    private fun tokenizer(): SentencePieceBpe {
        assumeTrue(
            "sentencepiece.model not found at ${modelFile.absolutePath} — the vendor artifact is gitignored",
            modelFile.isFile,
        )
        return SentencePieceBpe.load(modelFile)
    }

    // ---------------------------------------------------------------- the proto parses

    @Test
    fun `the model proto parses into the vocabulary the publisher shipped`() {
        val sp = tokenizer()

        assertEquals(262144, sp.size)
        assertEquals("<pad>", sp.piece(0))
        assertEquals("<eos>", sp.piece(1))
        assertEquals("<bos>", sp.piece(2))
        assertEquals("<unk>", sp.piece(3))
        assertEquals("<mask>", sp.piece(4))
    }

    @Test
    fun `the byte pieces are the ones SentencePiece puts at a fixed offset`() {
        // `<0xC2>` is id 432 and `<0xA0>` is 398, so the offset is 238 for every byte. Pinning it here means the
        // fallback path cannot silently drift to a different piece.
        val sp = tokenizer()

        assertEquals(432, sp.bytePiece(0xC2))
        assertEquals(398, sp.bytePiece(0xA0))
        assertEquals(238, sp.bytePiece(0x00))
        assertEquals(493, sp.bytePiece(0xFF))
    }

    @Test
    fun `the parse keeps the publisher's own scores`() {
        // These are merge ranks expressed as scores, which is why they look like -(id - 494) rather than like
        // log-probabilities. `▁▁` scores 0.0 — the best score in the model — which is exactly why it survives as one
        // piece instead of being split into two `▁`.
        val sp = tokenizer()

        assertEquals(-8765.0f, sp.score(9259), 0.01f)      // 'Hello'
        assertEquals(0.0f, sp.score(138), 0.01f)           // '▁▁'
        assertEquals(-155.0f, sp.score(649), 0.01f)        // '▁W'
        assertEquals(-236280.0f, sp.score(236743), 0.01f)  // '▁'
    }

    // ---------------------------------------------------------------- tokenization matches the oracle

    @Test
    fun `tokenization reproduces the publisher's own pieces`() {
        // Asserted on pieces rather than ids when something is wrong: an id mismatch tells you nothing about what
        // the tokenizer thought it saw.
        val sp = tokenizer()

        assertEquals(listOf("Hello", "\u2581World"), sp.encode("Hello World").map { sp.piece(it) })
    }

    @Test
    fun `tokenization reproduces the publisher's own ids`() {
        val sp = tokenizer()

        assertArrayEquals(intArrayOf(9259, 4109), sp.encode("Hello World"))
        assertArrayEquals(intArrayOf(144626, 236900, 12811), sp.encode("你好，世界"))
        assertArrayEquals(intArrayOf(123125, 236859), sp.encode("café"))
        assertArrayEquals(intArrayOf(236781, 255968, 236762), sp.encode("x\ty"))
        assertArrayEquals(intArrayOf(2413, 13655, 236743, 210555, 163601), sp.encode("EDITH 语义检索"))
    }

    @Test
    fun `a merge that loses on rank is not taken even when its pieces score better`() {
        // The sharpest difference between BPE and the unigram Viterbi this file used to drive. `EDIT` is one piece
        // at -41362, while `ED` (-1919) + `IT` (-1274) sum to -3193 — a max-sum Viterbi therefore splits it, and the
        // publisher does not. The piece count is asserted too, so the failure stays legible.
        val sp = tokenizer()

        assertArrayEquals(intArrayOf(41856), sp.encode("EDIT"))
        assertEquals("EDIT must survive as one piece", 1, sp.encode("EDIT").size)

        // The same shape twice more, from the same corpus: the oracle takes the longer merge.
        assertArrayEquals(intArrayOf(2413, 13655), sp.encode("EDITH"))
        assertArrayEquals(intArrayOf(123125, 236859), sp.encode("café"))
    }

    @Test
    fun `merges are applied until no adjacent pair is a piece`() {
        val sp = tokenizer()

        assertArrayEquals(intArrayOf(67997), sp.encode("embedding"))
        assertArrayEquals(intArrayOf(198329, 20257, 3516, 139245), sp.encode("SENTENCEPIECE"))
        assertArrayEquals(intArrayOf(602, 8145, 179086), sp.encode("unbelievable"))
        assertArrayEquals(intArrayOf(4243, 3986, 1111), sp.encode("retrieval"))
        assertArrayEquals(intArrayOf(212275, 547), sp.encode("Rokid"))
        assertArrayEquals(intArrayOf(8145, 703), sp.encode("belie"))
        assertArrayEquals(intArrayOf(108414, 3927), sp.encode("semantic search"))
    }

    @Test
    fun `normalization escapes spaces and does nothing else`() {
        // Three facts from the oracle, all of which a "reasonable" NFKC normalizer would get wrong:
        // no dummy prefix (`Hello` keeps its id, it is not `▁Hello`), whitespace is NOT collapsed, and full-width
        // characters survive untouched.
        val sp = tokenizer()

        assertArrayEquals(intArrayOf(138, 236746, 139, 236763, 138), sp.encode("  a   b  "))
        assertArrayEquals(intArrayOf(236776, 239549), sp.encode("AＡ"))
        assertNotEquals(
            "collapsing whitespace would make these equal",
            sp.encode("a  b").toList(),
            sp.encode("a b").toList(),
        )
        // and the oracle's actual values for that pair, so the inequality above cannot pass by both being wrong
        assertArrayEquals(intArrayOf(236746, 138, 236763), sp.encode("a  b"))
        assertArrayEquals(intArrayOf(236746, 518), sp.encode("a b"))
    }

    @Test
    fun `a character outside the vocabulary falls back to its utf-8 bytes`() {
        val sp = tokenizer()

        // U+00A0 is not a piece; NBSP is two UTF-8 bytes and both become byte pieces. The fallback is per byte and
        // applies only to a character with no piece at all — a character that does have one is never exploded.
        assertArrayEquals(intArrayOf(432, 398), sp.encode("\u00a0"))
        assertArrayEquals(intArrayOf(432, 398, 236746), sp.encode("\u00a0a"))
    }

    @Test
    fun `an empty text produces no pieces`() {
        val sp = tokenizer()

        assertArrayEquals(intArrayOf(), sp.encode(""))
    }

    @Test
    fun `the same text twice produces the same ids`() {
        val sp = tokenizer()

        assertArrayEquals(sp.encode("EDITH 语义检索"), sp.encode("EDITH 语义检索"))
    }

    // ---------------------------------------------------------------- the model's frame

    @Test
    fun `the frame wraps the text in bos and eos and pads to the sequence length`() {
        val sp = tokenizer()

        val ids = sp.encodeForModel("Hello World", sequenceLength = 256)

        assertEquals(256, ids.size)
        assertEquals(2, ids[0])
        assertArrayEquals(intArrayOf(9259, 4109), ids.copyOfRange(1, 3))
        assertEquals(1, ids[3])
        assertTrue("everything after eos is pad", ids.copyOfRange(4, 256).all { it == 0 })
    }

    @Test
    fun `a long text is truncated to the sequence length and keeps its frame`() {
        val sp = tokenizer()
        val long = "语义检索 ".repeat(200)

        val ids = sp.encodeForModel(long, sequenceLength = 256)

        assertEquals(256, ids.size)
        assertEquals(2, ids[0])
        assertEquals("the closing token must survive truncation, or the frame is not a frame", 1, ids[255])
    }

    @Test
    fun `an empty text still produces a complete frame`() {
        val sp = tokenizer()

        val ids = sp.encodeForModel("", sequenceLength = 256)

        assertEquals(256, ids.size)
        assertEquals(2, ids[0])
        assertEquals(1, ids[1])
        assertTrue(ids.copyOfRange(2, 256).all { it == 0 })
    }

    // ---------------------------------------------------------------- the USER_DEFINED pre-match

    @Test
    fun `a user defined symbol is matched whole rather than assembled from smaller pieces`() {
        // `bpe_model.cc` has two stages, and only the second was ported: before merging, it takes the longest
        // match against the pieces of type USER_DEFINED and freezes it. This model has **6410** of them (`<mask>`,
        // `[multimodal]`, `<ctrl1>`…`<ctrl3600>`, the run-length symbols), and the merge agenda cannot assemble
        // `<mask>` from `<` + `mask` + `>`, which is why the port used to split it.
        //
        // The previous session's reference encoder (`.local/t6b-bpe.py`) skipped this stage too, calling it "the
        // UNUSED pre-match" — it is not UNUSED (type 5, absent here) but USER_DEFINED (type 4), so its 68/69
        // headline never covered any of the strings below. Every expectation here is the publisher's own output.
        val sp = tokenizer()

        assertArrayEquals(intArrayOf(4), sp.encode("<mask>"))
        assertArrayEquals(intArrayOf(236746, 4, 236763), sp.encode("a<mask>b"))
        assertArrayEquals(intArrayOf(4, 236781), sp.encode("<mask>x"))
        assertArrayEquals(intArrayOf(236781, 4), sp.encode("x<mask>"))
        assertArrayEquals(intArrayOf(4, 4), sp.encode("<mask><mask>"))
        assertArrayEquals(intArrayOf(5), sp.encode("[multimodal]"))
    }

    @Test
    fun `the pre-match takes the longest user defined symbol and does not touch control symbols`() {
        val sp = tokenizer()

        // Greedy longest: `<ctrl10>` is one piece, not `<ctrl1>` + `0`.
        assertArrayEquals(intArrayOf(7), sp.encode("<ctrl1>"))
        assertArrayEquals(intArrayOf(16), sp.encode("<ctrl10>"))
        assertArrayEquals(intArrayOf(106), sp.encode("<ctrl100>"))
        assertArrayEquals(intArrayOf(259098), sp.encode("<ctrl319>"))

        // CONTROL symbols are NOT pre-matched — the publisher splits these, and so must we. `<mask>` is
        // USER_DEFINED (id 4) even though it lives in the same low id band, which is exactly the trap here.
        assertArrayEquals(intArrayOf(236820, 13039, 236813), sp.encode("<pad>"))
        assertArrayEquals(intArrayOf(236820, 211827, 236813), sp.encode("<eos>"))
        // Nothing matches without the closing bracket, so it falls back to the ordinary lattice.
        assertArrayEquals(intArrayOf(236820, 1080), sp.encode("<mask"))
    }

    // ---------------------------------------------------------------- the one-byte fallback

    @Test
    fun `a one byte character with no piece of its own still falls back to its byte piece`() {
        // The byte fallback is "one byte piece per UTF-8 byte, for a character with no piece at all". An earlier
        // guard (`bytes.size <= 1`) exempted every single-byte character, so those resolved through the vocabulary
        // lookup to `<unk>` instead. Control characters are the only place this is reachable: every printable
        // one-byte character has a piece of its own.
        val sp = tokenizer()

        assertArrayEquals(intArrayOf(238), sp.encode("\u0000"))
        assertArrayEquals(intArrayOf(242), sp.encode("\u0004"))
        assertArrayEquals(intArrayOf(249), sp.encode("\u000b"))
        assertArrayEquals(intArrayOf(251), sp.encode("\r"))

        // ...and a one-byte character that DOES have a piece is still never exploded.
        assertArrayEquals(intArrayOf(249732), sp.encode("\u0001"))
        assertArrayEquals(intArrayOf(255968), sp.encode("\t"))
    }

    // ---------------------------------------------------------------- the whole oracle corpus

    @Test
    fun `every case in the publisher corpus encodes identically`() {
        // Hand-picked literals pin the semantics; this pins the *breadth*. The corpus is generated by
        // `.local/t6b2-corpus.py` from the publisher's own encoder (7305 cases: the previous session's 69 strings,
        // every one of the model's 6410 USER_DEFINED surfaces, every one-byte code point, UTF-8 boundary code
        // points, runs of the space marker and newline, and seeded random strings over eight scripts). It is
        // gitignored vendor-derived data, so this test skips loudly when it is absent.
        val sp = tokenizer()
        assumeTrue(
            "corpus not found at ${corpusFile.absolutePath} — generate it with .local/t6b2-corpus.py",
            corpusFile.isFile,
        )

        val mismatches = ArrayList<String>()
        var cases = 0
        var disagreed = 0
        corpusFile.forEachLine { line ->
            if (line.isBlank()) return@forEachLine
            val tab = line.indexOf('\t')
            val text = String(unhex(line.substring(0, tab)), Charsets.UTF_8)
            val expected = line.substring(tab + 1).split(',').filter { it.isNotEmpty() }.map { it.toInt() }
            val got = sp.encode(text).toList()
            cases++
            if (got != expected) {
                disagreed++
                if (mismatches.size < 8) {
                    mismatches += "input=${text.replace("\u2581", "_")} expected=$expected got=$got"
                }
            }
        }

        assertTrue("the corpus file was empty", cases > 7000)
        assertEquals(
            "the port disagreed with the publisher's own encoder on $disagreed of $cases cases; " +
                "first differences:\n" + mismatches.joinToString("\n"),
            0,
            disagreed,
        )
    }

    private fun unhex(hex: String): ByteArray {
        val out = ByteArray(hex.length / 2)
        for (i in out.indices) {
            out[i] = ((Character.digit(hex[i * 2], 16) shl 4) or Character.digit(hex[i * 2 + 1], 16)).toByte()
        }
        return out
    }
}
