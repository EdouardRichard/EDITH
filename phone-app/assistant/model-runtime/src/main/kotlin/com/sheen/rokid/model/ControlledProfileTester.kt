package com.sheen.rokid.model

import com.sheen.rokid.plugin.*
import com.sheen.rokid.storage.ProfileRepository
import java.time.Clock
import com.sheen.rokid.contracts.*
import java.util.UUID

/**
 * The production probe tester (0.25 R76): one fixed synthetic request per capability, and the operation's evidence is
 * recorded for **the revision that actually answered**.
 *
 * Success is a `Terminal COMPLETED`; `FAILED`/`INCOMPLETE`/`DEADLINE` record `Failed`; `CANCELLED` records nothing
 * (the user withdrew the test, so it neither proves nor disproves the capability). The revision is captured before the
 * request and the repository refuses evidence for any revision that has since been edited, so a late terminal can never
 * verify a configuration the user already changed.
 *
 * The image probe's bytes live in the composition's artifact store: [probeImageRef] resolves that stored artifact's id
 * on the first image probe, and the client's one [MediaSource] turns it back into bytes at encode time. The provider is
 * a lambda rather than a generated byte string because the Android artifact store, not this JVM module, owns where
 * image bytes live.
 */
class ControlledProfileTester(
    private val client: ProfileProbeTransport,
    private val repository: ProfileRepository,
    private val clock: MonotonicClock,
    private val wallClock: Clock = Clock.systemUTC(),
    /**
     * Artifact id of the composition's fixed synthetic image; `null` makes the image probe refuse visibly.
     *
     * A lazy provider, not an id captured at construction: registering the bytes is an artifact-store write, and a
     * composition that never runs an image probe (or a JVM test whose context has no cache directory) must not create
     * one as a side effect of being assembled.
     */
    private val probeImageRef: (() -> String?)? = null,
) : ProfileTester {
    override fun testText(profileId: String, listener: (ModelStreamEvent) -> Unit): CancellationHandle {
        val profile = repository.get(profileId) ?: throw ContractError.ConfigurationRejected("Model configuration unavailable")
        val id = UUID.randomUUID().toString()
        val now = clock.nowNanos()
        val request = ModelRequest(EventEnvelope(SessionId("profile-probe:$profileId"), Generation(1), id, now, now),
            id, id, profile.id, profile.revision, "Reply briefly with plain text.", listOf(InputPart.Text("只回复测试通过")),
            emptyList(), OutputModality.TEXT, Long.MAX_VALUE)
        return client.probe(request) { event -> record(profileId, profile, "TEXT_REQUEST", event); listener(event) }
    }

    override fun testImage(profileId: String, listener: (ModelStreamEvent) -> Unit): CancellationHandle {
        val profile = repository.get(profileId) ?: throw ContractError.ConfigurationRejected("Model configuration unavailable")
        val imageRef = probeImageRef?.invoke() ?: throw ContractError.CapabilityMissing("Synthetic image unavailable")
        val id = UUID.randomUUID().toString()
        val now = clock.nowNanos()
        // A fixed image and a fixed one-word question: the probe proves the image operation, not the model's knowledge.
        val request = ModelRequest(EventEnvelope(SessionId("profile-probe:$profileId"), Generation(1), id, now, now),
            id, id, profile.id, profile.revision, "Reply briefly with plain text.",
            listOf(InputPart.Text("What is the dominant color of this image? Reply with one word."),
                InputPart.Image(imageRef)),
            emptyList(), OutputModality.TEXT, Long.MAX_VALUE)
        return client.probe(request) { event -> record(profileId, profile, "IMAGE_REQUEST", event); listener(event) }
    }

    /** Records the terminal's verdict for [operation] on [profile]'s revision — exactly the rules `testText` always had. */
    private fun record(profileId: String, profile: ModelProfile, operation: String, event: ModelStreamEvent) {
        if (event !is ModelStreamEvent.Terminal) return
        val state = when (event.end) {
            ModelEnd.COMPLETED -> VerificationState.Verified
            ModelEnd.FAILED, ModelEnd.INCOMPLETE, ModelEnd.DEADLINE -> VerificationState.Failed
            ModelEnd.CANCELLED -> null
        }
        if (state != null)
            repository.verify(profileId, CapabilityVerification(profile.revision, operation, state, wallClock.millis()))
    }
}
